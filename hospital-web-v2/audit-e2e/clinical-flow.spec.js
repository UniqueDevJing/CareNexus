import { test, expect } from '@playwright/test'
async function login(page, username) {
  await page.goto('./login')
  await page.getByPlaceholder('输入用户名').fill(username)
  await page.getByPlaceholder('输入密码', {exact:true}).fill('123456')
  await page.locator('button[type=submit]').click()
}
test('patient → nurse → booking → payment → doctor record → patient record', async({browser})=>{
  test.setTimeout(90000)
  const patientContext=await browser.newContext()
  const nurseContext=await browser.newContext()
  const doctorContext=await browser.newContext()
  const patient=await patientContext.newPage(), nurse=await nurseContext.newPage(), doctor=await doctorContext.newPage()
  try {
    await login(patient,'patient')
    await expect(patient).toHaveURL(/patient\/pre/)
    await patient.getByRole('button',{name:'开始对话',exact:true}).click()
    await patient.locator('textarea').first().fill('咳嗽一周，没有其他不适')
    await patient.getByRole('button',{name:'发送',exact:false}).click()
    await expect(patient.getByRole('button',{name:'生成就诊建议',exact:true})).toBeEnabled()
    const triageResponse=patient.waitForResponse(r=>r.url().includes('/patient/triage')&&r.request().method()==='POST')
    await patient.getByRole('button',{name:'生成就诊建议',exact:true}).click()
    const suggestion=(await (await triageResponse).json()).data
    await login(nurse,'nurse')
    await expect(nurse).toHaveURL(/nurse\/triage/)
    const queueRow=nurse.locator('button').filter({hasText:suggestion.queue_code}).first()
    await queueRow.click()
    await nurse.locator('textarea').fill('已核对症状和就诊信息，确认普通门诊安排')
    await nurse.getByRole('button',{name:'确认分诊',exact:false}).click()
    await patient.getByRole('button',{name:'刷新人工状态',exact:true}).click()
    await patient.getByRole('button',{name:'确认并预约挂号',exact:false}).click()
    await expect(patient.getByText('预约已完成',{exact:false})).toBeVisible()
    await patient.goto('./patient/bills')
    await patient.getByRole('button',{name:'立即支付',exact:false}).first().click()
    await patient.getByRole('button',{name:'确认支付',exact:true}).click()
    await expect(patient.getByText('支付成功',{exact:true})).toBeVisible()
    await login(doctor,'doctor')
    await expect(doctor).toHaveURL(/doctor\/console/)
    await doctor.locator('.patient-row').first().click()
    await doctor.getByPlaceholder('症状、持续时间与就诊原因').fill('质检主诉：咳嗽一周')
    await doctor.getByRole('button',{name:'保存草稿',exact:false}).click()
    await expect(doctor.getByText('草稿已保存',{exact:true})).toBeVisible()
    // 已有草稿后再修改，提交必须保留最后一次输入。
    await doctor.getByPlaceholder('明确或初步诊断').fill('质检病历，非真实医疗记录')
    await doctor.getByRole('button',{name:'提交并完成接诊',exact:false}).click()
    await expect(doctor.getByPlaceholder('明确或初步诊断')).toBeDisabled()
    await patient.goto('./patient/records')
    await patient.getByText('质检病历，非真实医疗记录',{exact:true}).first().click()
    await expect(patient.getByText('质检主诉：咳嗽一周',{exact:true}).last()).toBeVisible()
  } finally { await patientContext.close(); await nurseContext.close(); await doctorContext.close() }
})
